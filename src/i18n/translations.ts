export function getDirectionLabel(direction: SignalDirection, lang: Language): string {
  if (direction === 'LONG') return lang === 'fa' ? 'لانگ (خرید)' : 'LONG';
  if (direction === 'SHORT') return lang === 'fa' ? 'شورت (فروش)' : 'SHORT';
  return lang === 'fa' ? 'انتظار' : 'WAIT';
}

